export const API_DESCRIPTION = `
## Kono API — документация

REST API таск-трекера **Kono**: проекты (workspaces), задачи, подзадачи, комментарии, участники и AI-компаньон.

### Базовый URL

Все методы ниже начинаются с префикса \`/api\`.  

Пример: \`GET /api/health\` → \`http://localhost:3000/api/health\`

### Быстрый старт

1. **Зарегистрируйтесь** или **войдите** через раздел **Авторизация** → \`POST /api/auth/register\` или \`POST /api/auth/login\`.

2. Скопируйте поле \`token\` из ответа.

3. Нажмите **Authorize** (замок вверху справа) и вставьте: \`Bearer <ваш_token>\`.

4. Вызывайте защищённые методы — JWT подставится автоматически.

### Группы методов

| Раздел | Для чего |
| ------ | -------- |
| **Авторизация** | Регистрация и вход, получение JWT |
| **Состояние сервисов** | Health-check API, БД и LLM |
| **Проекты** | CRUD workspace (в UI — «проект», ключ \`K-XXXXXX\`) |
| **Участники** | Члены команды, приглашения, роли |
| **Задачи** | Список, создание, обновление, удаление |
| **Подзадачи** | Шаги внутри задачи |
| **Комментарии и activity** | Лента событий и комментарии к задаче |
| **AI-компаньон** | Чат с контекстом задач |
| **LLM-ключи** | Личные ключи OpenAI-compatible API |
| **Пользователь** | Удаление аккаунта |
| **Администрирование** | Только для админов (\`ADMIN_EMAILS\`) |

### Термины

- **Workspace** = **проект** в интерфейсе. Публичный ключ вида \`K-ABC123\` — для URL.

- **Activity** = запись в ленте задачи (комментарий или системное событие).

- **Приоритет** задачи хранится в поле \`tags\` (значения: «Срочный», «Высокий», «Средний», «Низкий»).

### Коды ответов

| Код | Значение |
| --- | -------- |
| \`200\` | Успех, тело — JSON |
| \`204\` | Успех, тело пустое |
| \`400\` | Ошибка валидации |
| \`401\` | Нет или неверный JWT |
| \`403\` | Нет доступа к ресурсу |
| \`404\` | Не найдено |
| \`409\` | Конфликт (например, email занят) |
| \`503\` | Сервис недоступен (БД или AI) |

### Формат ошибки

\`\`\`json
{
  "error": "forbidden",
  "message": "Недостаточно прав"
}
\`\`\`

### Роли в проекте

\`OWNER\` · \`ADMIN\` · \`EDITOR\` · \`COMMENTER\` · \`VIEWER\`

### Статусы задач

\`TODO\` (в очереди) · \`DONE\` (готово) · \`DEFERRED\` (отложено) · \`ISSUES\` (проблемы)
`.trim();

